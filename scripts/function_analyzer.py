# ---------------------------------------------------------------------------
# Languages and exclusions (spec sections 1.1, 3 and 4)
# ---------------------------------------------------------------------------

LANGUAGES = {
    ".py": "python", ".pyi": "python",
    ".js": "javascript", ".jsx": "javascript", ".mjs": "javascript", ".cjs": "javascript",
    ".ts": "typescript", ".tsx": "typescript", ".mts": "typescript", ".cts": "typescript",
    ".go": "go", ".java": "java", ".rs": "rust", ".kt": "kotlin", ".kts": "kotlin",
    ".rb": "ruby", ".php": "php", ".c": "c", ".h": "c", ".cc": "cpp", ".cpp": "cpp",
    ".cxx": "cpp", ".hpp": "cpp", ".hh": "cpp", ".cs": "csharp", ".swift": "swift",
}
# Languages whose line comments start with '#'. Elsewhere '#' is code
# (Rust attributes, C preprocessor).
HASH_COMMENT_LANGUAGES = {"python", "ruby", "php"}

EXCLUDED_DIRS = (
    "node_modules/", ".venv/", "venv/", "env/", ".env/", "build/", "dist/", "out/",
    "target/", "_build/", "vendor/", "vendored/", "third_party/", "third-party/",
    "generated/", "codegen/", ".generated/", ".next/", ".nuxt/", ".output/",
    "coverage/", ".coverage/", ".mypy_cache/", ".pytest_cache/", "__pycache__/",
    ".git/", ".hg/", ".svn/",
)
EXCLUDED_NAME_RES = [re.compile(p) for p in (
    r"\.min\.(js|css)$", r"\.bundle\.js$", r"\.chunk\.js$", r"\.generated\.", r"\.pb\.(go|cc|h)$",
    r"\.g\.dart$", r"\.freezed\.dart$", r"\.d\.ts$",
)]
TEST_NAME_RES = [re.compile(p) for p in (
    r"(^|/)test_[^/]*\.py$", r"_test\.py$", r"_test\.go$", r"\.(test|spec)\.(js|ts|tsx)$",
    r"(^|/)__tests__/",
)]
GENERATED_MARKERS = ("DO NOT EDIT", "auto-generated", "generated by", "Code generated", "@generated")


def exclusion_reason(path: str, source: str) -> str | None:
    """Return why the spec excludes this file, or None if it is scanned."""
    rel = path.replace(os.sep, "/")
    while rel.startswith("./"):
        rel = rel[2:]
    padded = "/" + rel
    for d in EXCLUDED_DIRS:
        if "/" + d in padded:
            return f"excluded directory {d}"
    for r in EXCLUDED_NAME_RES:
        if r.search(rel):
            return f"excluded file name ({r.pattern})"
    for r in TEST_NAME_RES:
        if r.search(rel):
            return "test file"
    head = "\n".join(source.splitlines()[:5])
    for marker in GENERATED_MARKERS:
        if marker.lower() in head.lower():
            return f"generated file ('{marker}')"
    lines = source.splitlines()
    if lines and max(len(l) for l in lines) > 500 and len(lines) * 1000 < 5 * len(source):
        return "minified file"
    return None


# ---------------------------------------------------------------------------
# Effective-LOC line classification (spec section 1.3)
# ---------------------------------------------------------------------------

def python_code_lines(source: str, tree: ast.AST) -> set[int]:
    """Return the 1-based lines holding Python code (not blank, comment or docstring)."""
    # Docstring tokens are skipped by position, so code sharing a line with a
    # docstring (`def f(): """doc"""; return 1`) still counts.
    docstrings = set()
    for node in ast.walk(tree):
        if isinstance(node, (ast.Module, ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef)):
            body = getattr(node, "body", [])
            if body and isinstance(body[0], ast.Expr) and isinstance(
                getattr(body[0], "value", None), ast.Constant
            ) and isinstance(body[0].value.value, str):
                docstrings.add((body[0].lineno, body[0].col_offset))
    code: set[int] = set()
    skip = {tokenize.COMMENT, tokenize.NL, tokenize.NEWLINE, tokenize.INDENT,
            tokenize.DEDENT, tokenize.ENDMARKER, tokenize.ENCODING}
    for tok in tokenize.generate_tokens(io.StringIO(source).readline):
        if tok.type in skip:
            continue
        if tok.type == tokenize.STRING and tok.start in docstrings:
            continue
        code.update(range(tok.start[0], tok.end[0] + 1))
    return code


def c_like_code_text(lines: list[str], language: str) -> list[str]:
    """Return each line with comments removed and string contents blanked.

    Handles `//` and `/* ... */` comments (Rust `///`/`//!` included; Rust
    block comments nest), double-quoted strings, Rust raw strings
    (`r#"..."#`), JS template literals, and single quotes (a string in JS/PHP
    and friends, a char literal or lifetime in Rust). `#` starts a comment
    only for languages in HASH_COMMENT_LANGUAGES. A string literal is kept as
    `""`, so a line holding only part of a string still counts as code.
    """
    hash_comments = language in HASH_COMMENT_LANGUAGES
    rust = language == "rust"
    out: list[str] = []
    block_depth = 0
    string_end = None  # closing delimiter while inside a multi-line string
    string_raw = False  # Rust raw strings and Go backtick strings have no escapes
    js = language in ("javascript", "typescript")
    for line in lines:
        buf = []
        i, n = 0, len(line)
        while i < n:
            if block_depth:
                if line.startswith("*/", i):
                    block_depth -= 1
                    i += 2
                elif rust and line.startswith("/*", i):
                    block_depth += 1
                    i += 2
                else:
                    i += 1
                continue
            if string_end is not None:
                if not string_raw and line[i] == "\\":
                    i += 2
                    continue
                if line.startswith(string_end, i):
                    i += len(string_end)
                    string_end = None
                    buf.append('""')
                else:
                    i += 1
                continue
            c = line[i]
            if line.startswith("//", i) or (hash_comments and c == "#"):
                break
            if js and c == "/" and not line.startswith("/*", i) and _regex_can_start(buf):
                j = _regex_end(line, i)
                if j:
                    buf.append("//")
                    i = j
                    continue
            if line.startswith("/*", i):
                block_depth = 1
                i += 2
                continue
            raw = re.match(r'(?:b|c)?r(#*)"', line[i:]) if rust else None
            if raw and (i == 0 or not (line[i - 1].isalnum() or line[i - 1] == "_")):
                string_end = '"' + raw.group(1)
                string_raw = True
                i += raw.end()
                continue
            if c == '"' or (c == "`" and not rust):
                string_end = c
                string_raw = c == "`" and language == "go"
                i += 1
                continue
            if c == "'":
                if rust:
                    m = re.match(r"'(?:\\.[^']*|[^\\'])'", line[i:])
                    if m:  # char literal; otherwise a lifetime
                        buf.append("''")
                        i += m.end()
                        continue
                else:
                    j = i + 1
                    while j < n and line[j] != "'":
                        j += 2 if line[j] == "\\" else 1
                    buf.append("''")
                    i = j + 1
                    continue
            buf.append(c)
            i += 1
        if string_end is not None:
            buf.append('""')  # line ends inside a multi-line string: still code
        out.append("".join(buf))
    return out


def _regex_can_start(buf: list[str]) -> bool:
    """A JS `/` starts a regex literal after an operator, opening bracket,
    keyword or line start; after an identifier, number or `)` it is division."""
    prev = "".join(buf).rstrip()
    if not prev:
        return True
    if re.search(r"(?:^|[^\w$])(?:return|typeof|case|do|else|in|of|void|yield|await)$", prev):
        return True
    return prev[-1] in "(,=:[!&|?{};+-*%<>~^"


def _regex_end(line: str, i: int) -> int:
    """Return the index after the regex literal starting at line[i] == "/",
    honouring escapes and `[...]` classes, or 0 if it does not close."""
    j, in_class = i + 1, False
    while j < len(line):
        ch = line[j]
        if ch == "\\":
            j += 2
            continue
        if ch == "[":
            in_class = True
        elif ch == "]":
            in_class = False
        elif ch == "/" and not in_class:
            j += 1
            while j < len(line) and line[j].isalpha():
                j += 1  # flags
            return j
        j += 1
    return 0


def c_like_code_lines(lines: list[str], language: str) -> set[int]:
    """Return the 1-based lines that hold code in a C-like language."""
    return {no for no, text in enumerate(c_like_code_text(lines, language), 1) if text.strip()}


def is_test_path(path: str) -> bool:
    """True for files under a `tests/` directory (spec 3.3). In this repo
    `crates/*/tests/` is product-test code: listed as `kind: test`, never a
    violation."""
    return "/tests/" in "/" + path.replace(os.sep, "/")


def make_record(path, language, name, start, end, code_lines, lines, threshold) -> dict:
    """Build one section-5 record for the span [start, end] (1-based, inclusive)."""
    span = range(start, end + 1)
    raw = len(span)
    loc = sum(1 for n in span if n in code_lines)
    # A whitespace-only line inside a multi-line string is string content, so
    # it counts as code, not blank; loc + blank + comment == raw always holds.
    blank = sum(
        1 for n in span if n not in code_lines and n <= len(lines) and not lines[n - 1].strip()
    )
    test = is_test_path(path)
    return {
        "path": path,
        "language": language,
        "kind": "test" if test else "function",
        "name": name,
        "span": {"start_line": start, "end_line": end},
        "loc": loc,
        "threshold": threshold,
        "violates": loc > threshold and not test,
        "raw_lines": raw,
        "blank_lines": blank,
        "comment_lines": raw - blank - loc,
    }



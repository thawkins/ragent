def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Report functions whose effective LOC exceeds a threshold "
                    "(docs/CODE_INDEX_SPEC.md)."
    )
    parser.add_argument("--file", help="Path to the source file to analyze.")
    parser.add_argument("--threshold", type=int, default=1000,
                        help="Effective-LOC threshold (default 1000); a function violates when loc > threshold.")
    parser.add_argument("--format", choices=["json", "text"], default="json",
                        help="Output format (default: json).")
    parser.add_argument("--only-violating", "--only-exceeding", dest="only_violating",
                        action="store_true", help="Only output functions that violate the threshold.")
    parser.add_argument("--self-test", action="store_true", help="Run the built-in checks and exit.")
    args = parser.parse_args(argv)

    if args.self_test:
        return self_test()
    if not args.file:
        parser.error("--file is required unless --self-test is given")
    if not os.path.isfile(args.file):
        print(f"error: file not found: {args.file}", file=sys.stderr)
        return 2

    results, reason = analyze_file(args.file, threshold=args.threshold)
    if args.only_violating:
        results = [r for r in results if r["violates"]]

    if args.format == "json":
        json.dump(results, sys.stdout, indent=2)
        sys.stdout.write("\n")
    elif reason:
        print(f"{args.file}: skipped ({reason})")
    elif not results:
        print("No functions found.")
    else:
        for r in results:
            flag = "  VIOLATES" if r["violates"] else ""
            s = r["span"]
            print(f"{r['path']}:{s['start_line']}-{s['end_line']}  {r['name']}  "
                  f"loc={r['loc']} raw={r['raw_lines']}{flag}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

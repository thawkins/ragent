def analyze_python(source, lines, path, threshold) -> list[dict]:
    tree = ast.parse(source, filename=path)
    code = python_code_lines(source, tree)
    results: list[dict] = []

    def walk(node, scope):
        for child in ast.iter_child_nodes(node):
            if isinstance(child, ast.ClassDef):
                walk(child, scope + [child.name])
            elif isinstance(child, (ast.FunctionDef, ast.AsyncFunctionDef)):
                start = child.lineno  # the def line (spec 1.3), not its decorators
                name = ".".join(scope + [child.name])
                results.append(make_record(path, "python", name, start, child.end_lineno,
                                           code, lines, threshold))
                walk(child, scope + [child.name])
            else:
                walk(child, scope)

    walk(tree, [])
    return results


_FUNC_RES = [
    # Rust: [pub[(..)]] [const|async|unsafe|extern "C"]* fn name
    re.compile(r'^\s*(?:pub(?:\([^)]*\))?\s+)?(?:(?:const|async|unsafe|default)\s+|extern\s+"[^"]*"\s+)*'
               r"fn\s+(?P<name>[A-Za-z_]\w*)"),
    # Go: func name( / func (recv) name(
    re.compile(r"^\s*func\s+(?:\([^)]*\)\s*)?(?P<name>[A-Za-z_]\w*)\s*[\[(]"),
    # JS/TS function declarations
    re.compile(r"^\s*(?:export\s+)?(?:default\s+)?(?:async\s+)?function\s*\*?\s*(?P<name>[A-Za-z_$][\w$]*)\s*\("),
    # Named arrow / function expression bound to a variable (spec 1.2 grey area)
    re.compile(r"^\s*(?:export\s+)?(?:const|let|var)\s+(?P<name>[A-Za-z_$][\w$]*)\s*=\s*"
               r"(?:async\s*)?(?:function\b|\([^)]*\)\s*=>|[A-Za-z_$][\w$]*\s*=>)"),
    # Java / C# / C-family / class methods: [modifiers] [type] name(...) {
    # At least one type or modifier word must precede the name, so a bare call
    # (`step();`) is not a definition.
    re.compile(r"^\s*(?P<pre>(?:[\w<>\[\],.*&:?]+\s+)+)(?P<name>[A-Za-z_]\w*)\s*\("),
]
# Each language uses only its own definition syntax: the C-family pattern
# would misread Rust `if let Some(x) = f() {` as a definition of `Some`.
_PATTERNS_BY_LANGUAGE = {
    "rust": [_FUNC_RES[0]],
    "go": [_FUNC_RES[1]],
    "javascript": [_FUNC_RES[2], _FUNC_RES[3], _FUNC_RES[4]],
    "typescript": [_FUNC_RES[2], _FUNC_RES[3], _FUNC_RES[4]],
}
_STATEMENT_WORDS = {"return", "new", "throw", "else", "await", "yield", "case", "delete", "typeof",
                    "if", "let", "while", "for", "match", "switch", "catch", "in", "mut", "ref"}
_NOT_FUNCTIONS = {"if", "for", "while", "switch", "catch", "return", "match", "loop", "else",
                  "new", "sizeof", "do", "try", "with", "elif", "case", "throw", "await"}


def _brace_end(lines: list[str], start_idx: int) -> int:
    """Return the 1-based line of the brace that closes the block opened at or after start_idx."""
    depth = 0
    started = False
    for i in range(start_idx, len(lines)):
        for ch in lines[i]:
            if ch == "{":
                depth += 1
                started = True
            elif ch == "}":
                depth -= 1
                if started and depth == 0:
                    return i + 1
    return len(lines)


def _body_start(clean: list[str], idx: int, col: int, max_lines: int = 60) -> int | None:
    """Return the 0-based line where the definition's body `{` opens, or None.

    Scans the signature from `col` on line `idx`, tracking `()`/`[]` nesting
    so `[u8; 32]` or `where` clauses do not end it. A `;` at nesting depth 0
    first means a body-less declaration or a call. Signatures may span many
    lines; the scan gives up after `max_lines`.
    """
    depth = 0
    for j in range(idx, min(idx + max_lines, len(clean))):
        text = clean[j][col:] if j == idx else clean[j]
        for ch in text:
            if ch in "([":
                depth += 1
            elif ch in ")]":
                depth -= 1
            elif depth <= 0 and ch == ";":
                return None
            elif depth <= 0 and ch == "{":
                return j
    return None


def analyze_generic(lines, path, language, threshold) -> list[dict]:
    """Regex + brace-matching scanner for brace-delimited languages."""
    clean = c_like_code_text(lines, language)
    code = {no for no, text in enumerate(clean, 1) if text.strip()}
    patterns = _PATTERNS_BY_LANGUAGE.get(language, [_FUNC_RES[4]])
    results: list[dict] = []
    for idx, line in enumerate(lines):
        if idx + 1 not in code:
            continue
        match = next((m for m in (r.match(clean[idx]) for r in patterns) if m), None)
        if not match:
            continue
        # Rust and Go patterns name the keyword explicitly, so `fn new` is real.
        if language not in ("rust", "go") and match.group("name") in _NOT_FUNCTIONS:
            continue
        pre = match.groupdict().get("pre") or ""
        if set(pre.split()) & _STATEMENT_WORDS:
            continue
        brace_line = _body_start(clean, idx, match.end())
        if brace_line is None:
            continue
        end = _brace_end(clean, brace_line)
        results.append(make_record(path, language, match.group("name"), idx + 1, end,
                                   code, lines, threshold))
    return results


def _try_lizard(path, lines, language, threshold) -> list[dict] | None:
    """Use lizard's function boundaries when it is installed."""
    try:
        import lizard  # type: ignore
    except ImportError:
        return None
    try:
        info = lizard.analyze_file(path)
    except Exception:  # lizard cannot parse this file: fall back to the scanner
        return None
    code = c_like_code_lines(lines, language)
    return [make_record(path, language, f.name, f.start_line, f.end_line, code, lines, threshold)
            for f in info.function_list]


# ---------------------------------------------------------------------------
# Public API
# ---------------------------------------------------------------------------

def analyze_file(
    path: str, threshold: int = 1000, rel_path: str | None = None
) -> tuple[list[dict], str | None]:
    """Analyze one file. Returns (records, skip_reason); skip_reason is set
    when the file is excluded, unsupported, unreadable or unparseable.

    `rel_path` is the repo-relative path the section-3 exclusions are judged
    on; it defaults to `path` relative to the current directory.
    """
    if rel_path is None:
        rel_path = os.path.relpath(path)
    language = LANGUAGES.get(os.path.splitext(path)[1].lower())
    try:
        with open(path, encoding="utf-8", errors="replace") as fh:
            source = fh.read()
    except OSError as exc:
        return [], f"unreadable: {exc}"
    reason = exclusion_reason(rel_path, source)
    if reason:
        return [], reason
    if language is None:
        return [], "language: unknown (skipped)"
    lines = source.splitlines()
    if language == "python":
        try:
            return analyze_python(source, lines, path, threshold), None
        except (SyntaxError, tokenize.TokenError) as exc:
            return [], f"unparseable: {exc}"
    lizard_records = _try_lizard(path, lines, language, threshold)
    if lizard_records is not None:
        return lizard_records, None
    return analyze_generic(lines, path, language, threshold), None



_PY_FIXTURE = '''\
def counted(x):
    """Docstring line one.

    Docstring line three.
    """
    # a comment

    y = x + 1  # trailing comment still counts
    return y
'''

_RS_FIXTURE = '''\
/// Doc comment.
#[inline]
pub fn counted(x: u32) -> u32 {
    // line comment
    /* block
       comment */

    let y = x + 1; /* trailing */
    y
}

fn call_site() {
    counted(1);
}

fn strings<'a>(s: &'a str) -> bool {
    let glob = "src/*.rs";
    let open = '{';
    s == glob && open == '{'
}

fn after() {
    let _ = 1;
}
'''


def self_test() -> int:
    """Check counting, the strict threshold and exclusions on small fixtures."""
    failures = []
    scratch = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "target", "temp")
    os.makedirs(scratch, exist_ok=True)
    with tempfile.TemporaryDirectory(dir=scratch) as tmp:
        def write(name, text):
            p = os.path.join(tmp, name)
            os.makedirs(os.path.dirname(p), exist_ok=True)
            with open(p, "w", encoding="utf-8") as fh:
                fh.write(text)
            return p

        py, _ = analyze_file(write("mod.py", _PY_FIXTURE), threshold=3, rel_path="mod.py")
        # span 1-9: def, y=..., return y are code -> loc 3; 3 is not > 3.
        if [(r["name"], r["loc"], r["raw_lines"], r["violates"]) for r in py] != [("counted", 3, 9, False)]:
            failures.append(f"python: {py}")
        py2, _ = analyze_file(write("mod2.py", _PY_FIXTURE), threshold=2, rel_path="mod2.py")
        if not (py2 and py2[0]["violates"]):
            failures.append(f"python strict threshold: {py2}")

        rs, _ = analyze_file(write("lib.rs", _RS_FIXTURE), threshold=1000, rel_path="lib.rs")
        got = {(r["name"], r["loc"]) for r in rs}
        # counted: pub fn, let y, y, closing brace -> 4; call_site: fn, call, brace -> 3.
        # strings: a "/*" in a string and '{' char literals must not hide code
        # or end the function early, and `'a` is a lifetime -> 5; after -> 3.
        if got != {("counted", 4), ("call_site", 3), ("strings", 5), ("after", 3)}:
            failures.append(f"rust: {rs}")

        for name in ("node_modules/x.js", "pkg/a.min.js", "tests_dir/test_x.py", "src/a.d.ts"):
            recs, reason = analyze_file(write(name, "function f() {\n}\n"), rel_path=name)
            if recs or not reason:
                failures.append(f"exclusion not applied: {name}")
        recs, reason = analyze_file(
            write("gen.rs", "// Code generated by x. DO NOT EDIT.\nfn f() {\n}\n"), rel_path="gen.rs"
        )
        if recs or not reason:
            failures.append("generated-file marker not applied")

        # Review cases (#53).
        py3, _ = analyze_file(write("inline.py", 'def f(): """doc"""; return 1\n\n@deco\ndef g():\n    return 2\n'),
                              rel_path="inline.py")
        if [(r["name"], r["loc"], r["span"]["start_line"]) for r in py3] != [("f", 1, 1), ("g", 2, 4)]:
            failures.append(f"python inline docstring / decorator span: {py3}")
        rs2, _ = analyze_file(write("edge.rs", (
            'fn raw() -> &\'static str {\n    r"\\"\n}\n'
            "fn arr(x: [u8; 32]) -> u8 {\n    x[0]\n}\n"
            "fn long(\n    a: u32,\n    b: u32,\n    c: u32,\n    d: u32,\n    e: u32,\n) -> u32\nwhere\n    u32: Copy,\n{\n    a\n}\n"
            "fn last() {}\n"
        )), rel_path="edge.rs")
        if [r["name"] for r in rs2] != ["raw", "arr", "long", "last"] or rs2[0]["span"]["end_line"] != 3:
            failures.append(f"rust raw string / [u8; N] / long signature: {rs2}")
        js, _ = analyze_file(write("re.js", "function a() {\n  const p = /[/*]/;\n  return p;\n}\nfunction b() {\n}\n"),
                             rel_path="re.js")
        if [(r["name"], r["loc"]) for r in js] != [("a", 4), ("b", 2)]:
            failures.append(f"js regex literal: {js}")
        java, _ = analyze_file(write("R.java", "class R {\n  public void run() { step();\n    more();\n  }\n}\n"),
                               rel_path="R.java")
        if [r["name"] for r in java] != ["run"]:
            failures.append(f"java body on signature line: {java}")
        tst, _ = analyze_file(write("crates/x/tests/t.rs", "fn t() {\n}\n"), threshold=0,
                              rel_path="crates/x/tests/t.rs")
        if [(r["kind"], r["violates"]) for r in tst] != [("test", False)]:
            failures.append(f"tests/ dir: {tst}")
        recs, reason = analyze_file(write("dot/a.js", "function f() {\n}\n"), rel_path=".next/a.js")
        if recs or not reason:
            failures.append("leading-dot directory not excluded")

    if failures:
        print("self-test FAILED")
        for f in failures:
            print("  ", f)
        return 1
    print("self-test ok")
    return 0



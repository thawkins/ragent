#!/usr/bin/env python3
"""
function_analyzer.py - function boundary detection and effective-LOC counting.

Implements the core of docs/CODE_INDEX_SPEC.md for a single source file:

- effective LOC (spec section 1.3): physical lines of a function's span minus
  blank lines and comment-only lines (line comments, block comments, Python
  docstrings);
- the strict threshold rule (section 2): ``violates`` iff ``loc > threshold``;
- the path, file-name, test-file and generated-file exclusions (section 3);
- the output fields of section 5, with ``raw_lines``, ``blank_lines`` and
  ``comment_lines`` as enrichment.

Python is parsed with the stdlib ``ast`` and ``tokenize``. Other languages use
``lizard`` when it is installed, otherwise a regex + brace-matching scanner
(Rust ``fn``, Go ``func``, JS/TS, Java, C-family). Not implemented from the
spec: tree-sitter parsing, module-level records and ``--spec-check``.

Usage:
    python3 scripts/function_analyzer.py --file path.rs [--threshold 1000]
    python3 scripts/function_analyzer.py --file app.ts --only-violating
    python3 scripts/function_analyzer.py --self-test

Output (JSON array, one object per function):
    {
        "path": "src/lib.rs",
        "language": "rust",
        "kind": "function",
        "name": "Parser::parse",
        "span": {"start_line": 10, "end_line": 42},
        "loc": 28,
        "threshold": 1000,
        "violates": false,
        "raw_lines": 33,
        "blank_lines": 3,
        "comment_lines": 2
    }

An excluded file yields an empty array (``--format text`` says why).
"""
from __future__ import annotations

import argparse
import ast
import io
import json
import os
import re
import sys
import tempfile
